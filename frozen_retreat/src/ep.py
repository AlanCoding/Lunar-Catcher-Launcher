"""Electric propulsion helpers for the frozen retreat trade study."""

from __future__ import annotations

import math


def mass_ratio(dv_m_s: float, ve_m_s: float) -> float:
    """Return rocket equation mass ratio m0/m1.

    Inputs:
    - dv_m_s [m/s]
    - ve_m_s [m/s]
    """
    assert dv_m_s >= 0.0
    assert ve_m_s > 0.0
    return math.exp(dv_m_s / ve_m_s)


def thrust_for_impulse(mass_kg: float, dv_m_s: float, time_s: float) -> float:
    """Return average thrust required to provide mass*dv over time.

    Inputs:
    - mass_kg [kg]
    - dv_m_s [m/s]
    - time_s [s]

    Output:
    - thrust [N]
    """
    assert mass_kg >= 0.0
    assert dv_m_s >= 0.0
    assert time_s > 0.0
    return mass_kg * dv_m_s / time_s


def ep_power_for_thrust_W(thrust_N: float, ve_m_s: float, eta: float) -> float:
    """Return electric power needed for thrust, in watts.

    Uses P = T*ve/(2*eta).

    Inputs:
    - thrust_N [N]
    - ve_m_s [m/s]
    - eta [unitless]
    """
    assert thrust_N >= 0.0
    assert ve_m_s > 0.0
    assert 0.0 < eta <= 1.0
    return thrust_N * ve_m_s / (2.0 * eta)


def thrust_from_ep_power_N(power_W: float, ve_m_s: float, eta: float) -> float:
    """Return thrust generated by given EP power.

    Uses T = 2*eta*P/ve.

    Inputs:
    - power_W [W]
    - ve_m_s [m/s]
    - eta [unitless]
    """
    assert power_W >= 0.0
    assert ve_m_s > 0.0
    assert 0.0 < eta <= 1.0
    return 2.0 * eta * power_W / ve_m_s
